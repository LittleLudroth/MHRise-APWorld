def resolve_default_input() -> Path:
    """Look in <game install>/reframework/data, then cwd."""
    game = os.environ.get("AP_GAME_INSTALL")
    if game:
        p = Path(game) / "reframework" / "data" / DEFAULT_JSON_NAME
        if p.exists():
            return p
    return Path(DEFAULT_JSON_NAME)


def format_enum_value(
    raw: int | None,
    enum_name: str,
    members: dict[str, int],
    unknowns: dict[str, set[int]],
) -> str:
    """Return a source-code-ready expression for an enum value.

    Known integer → `EnumName.MEMBER`. Unknown integer → raw int with
    a comment, also recorded in `unknowns[enum_name]` for the run
    summary.
    """
    if raw is None:
        return "None"
    # Reverse lookup: value → name. For flag enums with combinations
    # we fall back to int (no observed combos in catalog, but defensive).
    name_by_value = {v: k for k, v in members.items()}
    if raw in name_by_value:
        return f"{enum_name}.{name_by_value[raw]}"
    unknowns.setdefault(enum_name, set()).add(raw)
    return f"{raw}  # unknown {enum_name}"


def convert(catalog_path: Path) -> None:
    print(f"reading {catalog_path}", file=sys.stderr)
    with catalog_path.open(encoding="utf-8") as f:
        catalog = json.load(f)

    weapons_in = catalog["weapons"] or []
    print(f"  {len(weapons_in)} raw entries", file=sys.stderr)

    kept: list[dict] = []

    for w in weapons_in:
        kept.append({
            "weapon_id": w["weapon_id"],
            "weapon_name": w["weapon_name"],
            "weapon_type": w["weapon_type"],
            "element_type": w["element_type"],
            "rarity": w["rarity"],
        })

    kept.sort(key=lambda r: (r["weapon_type"], r["rarity"]))

    print(f"  kept: {len(kept)}", file=sys.stderr)

    unknowns: dict[str, set[int]] = {}
    write_module(kept, catalog_path, unknowns)
    print(f"wrote {OUTPUT_PATH}", file=sys.stderr)
    if unknowns:
        print("  unknown enum values encountered (kept as raw int):",
              file=sys.stderr)
        for ename, vals in sorted(unknowns.items()):
            print(f"    {ename}: {sorted(vals)}", file=sys.stderr)


def emit_enum_class(
    name: str,
    members: dict[str, int],
    base: str,
) -> str:
    lines = [f"class {name}({base}):"]
    for member_name, value in members.items():
        lines.append(f"    {member_name} = {value}")
    return "\n".join(lines) + "\n"


def write_module(
    weapons: list[dict],
    source_path: Path,
    unknowns: dict[str, set[int]],
) -> None:
    header = f'''"""Master weapon data table for the MH Rise Archipelago world.

Single source of truth for which weapons exist in the game.
Generated by `debug_tools/convert_weapon_data.py`
from a snapshot of the in-game quest catalog (dumped via
`debug_tools/WeaponDataDump.lua`). Do NOT hand-edit — regenerate.

Source snapshot: {source_path.name}
Total weapons: {len(weapons)}


Fields per entry:
- "weapon_id": in-game weapon identifier
- "weapon_name": in-game name for the weapon
- "weapon_type": in-game type of the weapon
- "element_type": in-game type of the weapon's primary element
- "rarity": in-game rarity of the armor piece
"""
from __future__ import annotations
from enum import IntEnum
from typing import Any


'''

    enums_block = (
        emit_enum_class("Rarity", RARE_TYPE_MEMBERS, "IntEnum")
        + "\n"
        + emit_enum_class("WeaponType", WEAPON_TYPE_MEMBERS, "IntEnum")
        + "\n"
        + emit_enum_class("ElementType", ELEMENT_TYPE_MEMBERS, "IntEnum")
        + "\n"
    )

    body_lines: list[str] = ["WEAPON_DATA: tuple[dict[str, Any], ...] = ("]
    for w in weapons:
        rare = format_enum_value(
            w["rarity"], "Rarity", RARE_TYPE_MEMBERS, unknowns)
        wt = format_enum_value(
            w["weapon_type"], "WeaponType", WEAPON_TYPE_MEMBERS, unknowns)
        elem = format_enum_value(
            w["element_type"], "ElementType", ELEMENT_TYPE_MEMBERS, unknowns)
        body_lines.append("    {")
        body_lines.append(f'        "weapon_id": {w["weapon_id"]!r},')
        body_lines.append(f'        "weapon_name": {w["weapon_name"]!r},')
        body_lines.append(f'        "weapon_type": {wt},')
        body_lines.append(f'        "element_type": {elem},')
        body_lines.append(f'        "rarity": {rare},')
        body_lines.append("    },")
    body_lines.append(")")

    OUTPUT_PATH.write_text(
        header + enums_block + "\n" + "\n".join(body_lines) + "\n",
        encoding="utf-8",
    )

def main() -> None:
    if len(sys.argv) >= 2:
        path = Path(sys.argv[1])
    else:
        path = resolve_default_input()
    if not path.exists():
        print(f"ERROR: catalog JSON not found at {path}", file=sys.stderr)
        print("Pass the path as the first argument, or set AP_GAME_INSTALL.",
              file=sys.stderr)
        sys.exit(1)
    convert(path)

if __name__ == "__main__":
    main()