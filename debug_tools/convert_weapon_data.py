"""Convert mhrise_weapon_data.json (from WeaponDataDump.lua) into
ap_world/data/weapon_data.py.

One-time script — runs offline, reads a checked-in JSON snapshot, writes
a Python module. Re-run when Capcom drops a DLC patch that adds weapons
(re-dump in-game with WeaponDataDump.lua first).

Output module exports:
- Rarity (IntEnum), WeaponType (IntEnum), ElementType (IntEnum) — mirror the in-game enums from
  snow.data.*
- WEAPON_DATA: tuple of dicts. Rarity, Weapon_Type, Element_Type values are the enum members, NOT raw ints. Unknown raw values
  fall back to the int with a comment.

Usage:
    python debug_tools/convert_weapon_data.py [INPUT_JSON]

INPUT_JSON defaults to a path under the env-var AP_GAME_INSTALL
(reframework/data/mhrise_weapon_data.json) when present, otherwise
to ./mhrise_weapon_data.json.
"""

