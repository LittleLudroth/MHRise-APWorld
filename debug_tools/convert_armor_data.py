"""Convert mhrise_armor_data.json (from ArmorDataDump.lua) into
ap_world/data/armor_data.py.

One-time script — runs offline, reads a checked-in JSON snapshot, writes
a Python module. Re-run when Capcom drops a DLC patch that adds armor
(re-dump in-game with ArmorDataDump.lua first).

Output module exports:
- Rarity (IntEnum), SexType (IntEnum), ArmorSlot (IntEnum) — mirror the in-game enums from
  snow.data.*
- ARMOR_DATA: tuple of dicts. Rarity, Sex_Type, Armor_Slot values are the enum members, NOT raw ints. Unknown raw values
  fall back to the int with a comment.

Usage:
    python debug_tools/convert_armor_data.py [INPUT_JSON]

INPUT_JSON defaults to a path under the env-var AP_GAME_INSTALL
(reframework/data/mhrise_armor_data.json) when present, otherwise
to ./mhrise_armor_data.json.
"""

from __future__ import annotations

import importlib.util
import json
import os
import sys
from pathlib import Path
from types import ModuleType

REPO_ROOT = Path(__file__).resolve().parent.parent

OUTPUT_PATH = REPO_ROOT / "ap_world" / "data" / "armor_data.py"
DEFAULT_JSON_NAME = "mhrise_armor_data.json"

# snow.data.DataDef.RareTypes
RARE_TYPE_MEMBERS: dict[str, int] = {
    "Ra1":0,
    "Ra2":1,
    "Ra3":2,
    "Ra4":3,
    "Ra5":4,
    "Ra6":5,
    "Ra7":6,
    "Ra8":7,
    "Ra9":8,
    "Ra10":9,
}

# snow.data.GameItemEnum.SexualEquipableFlag
SEX_TYPE_MEMBERS: dict[str, int] = {
    "MaleOnly":0,
    "FemaleOnly":1,
    "Both":2,
}

# Armor Slot
ARMOR_TYPE_MEMBERS: dict[str, int] = {
    "Head":0,
    "Chest":1,
    "Arms":2,
    "Waist":3,
    "Legs":4
}

def resolve_default_input() -> Path:
    """Look in <game install>/reframework/data, then cwd."""
    game = os.environ.get("AP_GAME_INSTALL")
    if game:
        p = Path(game) / "reframework" / "data" / DEFAULT_JSON_NAME
        if p.exists():
            return p
    return Path(DEFAULT_JSON_NAME)


def format_enum_value(
    raw: int | None,
    enum_name: str,
    members: dict[str, int],
    unknowns: dict[str, set[int]],
) -> str:
    """Return a source-code-ready expression for an enum value.

    Known integer → `EnumName.MEMBER`. Unknown integer → raw int with
    a comment, also recorded in `unknowns[enum_name]` for the run
    summary.
    """
    if raw is None:
        return "None"
    # Reverse lookup: value → name. For flag enums with combinations
    # we fall back to int (no observed combos in catalog, but defensive).
    name_by_value = {v: k for k, v in members.items()}
    if raw in name_by_value:
        return f"{enum_name}.{name_by_value[raw]}"
    unknowns.setdefault(enum_name, set()).add(raw)
    return f"{raw}  # unknown {enum_name}"


def convert(catalog_path: Path) -> None:
    print(f"reading {catalog_path}", file=sys.stderr)
    with catalog_path.open(encoding="utf-8") as f:
        catalog = json.load(f)

    armors_in = catalog["armors"] or []
    print(f"  {len(armors_in)} raw entries", file=sys.stderr)

    kept: list[dict] = []

    for a in armors_in:
        kept.append({
            "armor_id": a["armor_id"],
            "armor_name": a["armor_name"],
            "armor_slot": a["armor_slot"],
            "sex_type": a["sex_type"],
            "rarity": a["rarity"],
        })

    kept.sort(key=lambda r: (r["armor_slot"], r["rarity"]))

    print(f"  kept: {len(kept)}", file=sys.stderr)

    unknowns: dict[str, set[int]] = {}
    write_module(kept, catalog_path, unknowns)
    print(f"wrote {OUTPUT_PATH}", file=sys.stderr)
    if unknowns:
        print("  unknown enum values encountered (kept as raw int):",
              file=sys.stderr)
        for ename, vals in sorted(unknowns.items()):
            print(f"    {ename}: {sorted(vals)}", file=sys.stderr)


def emit_enum_class(
    name: str,
    members: dict[str, int],
    base: str,
) -> str:
    lines = [f"class {name}({base}):"]
    for member_name, value in members.items():
        lines.append(f"    {member_name} = {value}")
    return "\n".join(lines) + "\n"


def write_module(
    armor: list[dict],
    source_path: Path,
    unknowns: dict[str, set[int]],
) -> None:
    header = f'''"""Master armor table for the MH Rise Archipelago world.

Single source of truth for which armor pieces exist in the game.
Generated by `debug_tools/convert_armor_data.py`
from a snapshot of the in-game quest catalog (dumped via
`debug_tools/ArmorDataDump.lua`). Do NOT hand-edit — regenerate.

Source snapshot: {source_path.name}
Total armor pieces: {len(armor)}


Fields per entry:
- "armor_id": in-game armor piece identifier
- "armor_name": in-game name for the armor piece
- "armor_slot": what armor slot the piece is for
- "sex_type": in-game flag detailing which player sex can equip the armor
- "rarity": in-game rarity of the armor piece
"""
from __future__ import annotations
from enum import IntEnum
from typing import Any


'''

    enums_block = (
        emit_enum_class("Rarity", RARE_TYPE_MEMBERS, "IntEnum")
        + "\n"
        + emit_enum_class("SexType", SEX_TYPE_MEMBERS, "IntEnum")
        + "\n"
        + emit_enum_class("ArmorSlot", ARMOR_TYPE_MEMBERS, "IntEnum")
        + "\n"
    )

    body_lines: list[str] = ["ARMOR_DATA: tuple[dict[str, Any], ...] = ("]
    for a in armor:
        rare = format_enum_value(
            a["rarity"], "Rarity", RARE_TYPE_MEMBERS, unknowns)
        sex = format_enum_value(
            a["sex_type"], "SexType", SEX_TYPE_MEMBERS, unknowns)
        slot = format_enum_value(
            a["armor_slot"], "ArmorSlot", ARMOR_TYPE_MEMBERS, unknowns)
        body_lines.append("    {")
        body_lines.append(f'        "armor_id": {a["armor_id"]!r},')
        body_lines.append(f'        "armor_name": {a["armor_name"]!r},')
        body_lines.append(f'        "armor_slot": {slot},')
        body_lines.append(f'        "sex_type": {sex},')
        body_lines.append(f'        "rarity": {rare},')
        body_lines.append("    },")
    body_lines.append(")")

    OUTPUT_PATH.write_text(
        header + enums_block + "\n" + "\n".join(body_lines) + "\n",
        encoding="utf-8",
    )

def main() -> None:
    if len(sys.argv) >= 2:
        path = Path(sys.argv[1])
    else:
        path = resolve_default_input()
    if not path.exists():
        print(f"ERROR: catalog JSON not found at {path}", file=sys.stderr)
        print("Pass the path as the first argument, or set AP_GAME_INSTALL.",
              file=sys.stderr)
        sys.exit(1)
    convert(path)

if __name__ == "__main__":
    main()